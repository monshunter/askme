const catalogs: Record<Locale, Record<TranslationKey, string>> = { en: english, "zh-CN": chinese };

export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && (SUPPORTED_LOCALES as readonly string[]).includes(value);
}

export function normalizeLocale(value: unknown): Locale {
  return isLocale(value) ? value : DEFAULT_LOCALE;
}

export function translate(locale: Locale, key: TranslationKey, parameters: Record<string, string | number> = {}) {
  const template = catalogs[locale][key] ?? english[key];
  return Object.entries(parameters).reduce((copy, [name, value]) => copy.replaceAll(`{${name}}`, String(value)), template);
}

export function createTranslator(locale: Locale) {
  return (key: TranslationKey, parameters: Record<string, string | number> = {}) => translate(locale, key, parameters);
}

export function localeCookieOptions(secure: boolean) {
  return {
    httpOnly: true,
    maxAge: 60 * 60 * 24 * 365,
    path: "/",
    sameSite: "lax" as const,
    secure,
  };
}
